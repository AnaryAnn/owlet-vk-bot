def append_overplan_comment(message, plan, fact, report_id=None):
    if not fact > plan:
        return message
    # Разные отчёты получают случайный выбор, повтор одного — прежнюю фразу.
    rng = random.Random(str(report_id)) if report_id else random.SystemRandom()
    return message + '\n\n' + rng.choice(OVERPLAN_COMMENTS)
